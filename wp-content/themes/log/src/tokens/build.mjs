#!/usr/bin/env node
/**
 * Token generator. Reads src/tokens/tokens.json (the one source) and writes:
 *   src/styles/tokens.gen.css  custom properties on :root, imported by tokens.css
 *   assets/brand/tokens.css    the same file, shipped (src/ isn't deployed) for pages that stand outside the
 *                              build: log-core's coming-soon gate inlines it
 *   src/tokens/tokens.js       the same values for JS (the 3D map, MapLibre, drawings, the /brand book)
 *   DESIGN.md                  the `colors:` block of its frontmatter (the prose stays hand-written)
 *
 * Runs before every build (npm "prebuild"), so a value changed in tokens.json reaches all three.
 * `node src/tokens/build.mjs --check` exits 1 if any generated file is out of date.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const theme = resolve(here, '../..');
const files = {
  json: resolve(here, 'tokens.json'),
  css: resolve(theme, 'src/styles/tokens.gen.css'),
  shipped: resolve(theme, 'assets/brand/tokens.css'),
  js: resolve(here, 'tokens.js'),
  design: resolve(theme, '../../../DESIGN.md'),
};
const check = process.argv.includes('--check');

const source = JSON.parse(readFileSync(files.json, 'utf8'));
const groups = Object.entries(source).filter(([k]) => !k.startsWith('$'));
const read = (v) => (v !== null && typeof v === 'object' ? v : { value: v });
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const header = (c) => `${c} Generated by src/tokens/build.mjs from src/tokens/tokens.json. Do not edit by hand.`;

// CSS
let css = `/*${header('')} */\n:root {\n`;
for (const [group, entries] of groups) {
  css += `  /* ${group} */\n`;
  for (const [name, raw] of Object.entries(entries)) {
    const { value, note } = read(raw);
    css += `  --${name}: ${value};${note ? ` /* ${note} */` : ''}\n`;
  }
}
css += '}\n';

// JS: one object per group, camelCase keys; color and map merge into `color` for the scenes.
const js = {};
for (const [group, entries] of groups) {
  const out = (js[group === 'map' ? 'color' : group] ||= {});
  for (const [name, raw] of Object.entries(entries)) out[camel(name)] = read(raw).value;
}
let jsText = `//${header('')}\n`;
for (const [group, obj] of Object.entries(js)) {
  jsText += `export const ${group} = ${JSON.stringify(obj, null, 2).replace(/"([a-zA-Z0-9]+)":/g, '$1:')};\n`;
}
jsText += `/** A token colour (#rrggbb) at an opacity, as rgba() for canvas, WebGL and MapLibre paint. */
export function alpha(hex, a) {
  const n = parseInt(hex.slice(1), 16);
  return \`rgba(\${n >> 16}, \${(n >> 8) & 255}, \${n & 255}, \${a})\`;
}
/** Two token colours mixed in sRGB, t the share of b, as #rrggbb: the shades a drawing needs between two tokens. */
export function mix(a, b, t = 0.5) {
  const x = parseInt(a.slice(1), 16), y = parseInt(b.slice(1), 16);
  const c = (s) => Math.round(((x >> s) & 255) * (1 - t) + ((y >> s) & 255) * t);
  return '#' + ((1 << 24) | (c(16) << 16) | (c(8) << 8) | c(0)).toString(16).slice(1);
}
`;
jsText += `export default { ${Object.keys(js).join(', ')}, alpha, mix };\n`;

// DESIGN.md: replace the colors block (from "colors:" to the next top-level key) inside the frontmatter.
let design = existsSync(files.design) ? readFileSync(files.design, 'utf8') : null;
if (design) {
  const block = ['colors:', ...['color', 'map'].flatMap((g) =>
    Object.entries(source[g]).map(([n, raw]) => `  ${n}: "${read(raw).value}"`))].join('\n') + '\n';
  design = design.replace(/^colors:\n(?:  .*\n)+/m, block);
}

const outputs = [[files.css, css], [files.shipped, css], [files.js, jsText], ...(design ? [[files.design, design]] : [])];
let stale = 0;
for (const [path, text] of outputs) {
  const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
  if (current === text) continue;
  if (check) { console.error(`tokens: ${path} is out of date, run npm run tokens`); stale++; }
  else { writeFileSync(path, text); console.log(`tokens: wrote ${path.replace(theme + '/', '')}`); }
}
process.exit(stale ? 1 : 0);
